export function englishBuiltinLabel(label: string): string {
  if (Object.prototype.hasOwnProperty.call(labels, label)) return labels[label];
  const [base, suffix] = label.split(' · ');
  if (suffix && Object.prototype.hasOwnProperty.call(labels, base))
    return `${labels[base]} · ${suffix === 'campo' ? 'field' : suffix === 'quadro' ? 'panel' : suffix}`;
  return label
    .replace(/^Trasmettitore /, 'Transmitter ')
    .replace(/^Cavo (\d+) conduttori$/, 'Cable · $1 conductors')
    .replace(/^Interruttore (\d+)P · unifilare$/, 'Circuit breaker $1P · single-line');
}
